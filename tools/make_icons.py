"""Regenerates the Android VectorDrawable resources from icon/*.svg.

Android's <vector> format is not SVG: the crashing "<VectorGraphic> tag requires
viewportWidth > 0" came from shipping raw <svg> XML in res/drawable. This script
converts them properly and also builds the adaptive launcher icon layers.

Run from the repo root: python3 tools/make_icons.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
DRAWABLE = RES / "drawable"
DRAWABLE.mkdir(parents=True, exist_ok=True)

ICON = ROOT / "icon/void_icon.svg"
INNER = ROOT / "icon/void_inner_icon.svg"

FULL_SIDE = 2618          # void_icon.svg canvas
INNER_LEFT, INNER_TOP = 409, 409   # void_inner_icon.svg canvas
INNER_SIDE = 1800

HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/make_icons.py from {src} - do not edit by hand. -->\n')
VECTOR_OPEN = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
               '    xmlns:aapt="http://schemas.android.com/aapt"\n'
               '    android:width="{w}dp"\n'
               '    android:height="{h}dp"\n'
               '    android:viewportWidth="{vw}"\n'
               '    android:viewportHeight="{vh}">\n')


def stripped(svg_path):
    s = pathlib.Path(svg_path).read_text()
    s = re.sub(r"<metadata>.*?</metadata>", "", s, flags=re.S)
    return s.replace(' xmlns:c2pa="http://c2pa.org/manifest"', "")


def mark_path(svg_path=INNER):
    """The single white 'V' path inside void_inner_icon.svg."""
    d = re.search(r'd="([^"]+)"', stripped(svg_path)).group(1)
    return re.sub(r"\s+", " ", d).strip()


def color_of(svg_path):
    return re.search(r'fill="(#[0-9A-Fa-f]{6})"', stripped(svg_path)).group(1).lower()


def write(name, body, src):
    out = DRAWABLE / f"{name}.xml"
    out.write_text(HEADER.format(src=src) + body)
    print(f"  {out.relative_to(ROOT)} ({out.stat().st_size} B)")


# --- 1. Full mark (brand red tile + white V) as a launcher / logo drawable -----
red = color_of(ICON)
write(
    "void_icon",
    VECTOR_OPEN.format(w="108", h="108", vw=FULL_SIDE, vh=FULL_SIDE)+
    f'    <path\n        android:fillColor="{red}"\n'
    f'        android:pathData="M0,0h{FULL_SIDE}v{FULL_SIDE}h-{FULL_SIDE}z" />\n'
    f'    <path\n        android:fillColor="#ffffffff"\n'
    f'        android:pathData="{mark_path()}" />\n'
    "</vector>\n",
    "icon/void_icon.svg",
)

# --- 2. Inner mark only (the app's circle glyph) ------------------------------
# Keep the original 1800x1800 canvas and translate the art up by its 409 offset,
# so the mark fills the viewport exactly like it does in the SVG.
write(
    "void_inner_icon",
    VECTOR_OPEN.format(w="24", h="24", vw=INNER_SIDE, vh=INNER_SIDE)+
    "    <group android:translateX=\"-409\" android:translateY=\"-409\">\n"
    f'        <path\n            android:fillColor="#ffffffff"\n'
    f'            android:pathData="{mark_path()}" />\n'
    "    </group>\n"
    "</vector>\n",
    "icon/void_inner_icon.svg",
)

# --- 3. Adaptive icon foreground: white V centred in the 108dp safe zone ------
# A <group> cannot carry two android:translateX attributes, so the scale-about-
# centre transform is nested: translate(+c) -> scale(s) -> translate(-c).
# The mark's art is centred on (1309, 1309) in the 2618 canvas; 0.78 keeps it
# comfortably inside the 72dp visible mask of the 108dp adaptive icon.
SCALE = 0.78
C = FULL_SIDE / 2
write(
    "ic_launcher_foreground",
    VECTOR_OPEN.format(w="108", h="108", vw=FULL_SIDE, vh=FULL_SIDE)+
    f'    <group android:translateX="{C:.1f}" android:translateY="{C:.1f}">\n'
    f'        <group android:scaleX="{SCALE}" android:scaleY="{SCALE}">\n'
    f'            <group android:translateX="{-C:.1f}" android:translateY="{-C:.1f}">\n'
    f'                <path\n                    android:fillColor="#ffffffff"\n'
    f'                    android:pathData="{mark_path()}" />\n'
    "            </group>\n"
    "        </group>\n"
    "    </group>\n"
    "</vector>\n",
    "icon/void_icon.svg + icon/void_inner_icon.svg",
)

print("done")
