"""Generates app/src/main/kotlin/dev/voidapp/ui/icons/Lucide.kt

Path data is taken verbatim from the Lucide sources in
https://github.com/thelacspace/lucide-compose (v1.16.0). The published artifact on
Maven Central only ships the generator's test icons, so the app inlines them.

Usage:  python3 tools/gen_lucide.py <path-to-lucide-compose-checkout>
"""
import pathlib
import re
import sys

ICONS = [
    "ArrowLeft", "ArrowRight", "ChevronLeft", "ChevronRight", "Ellipsis", "X",
    "Search", "Plus", "House", "RotateCw", "Share2", "Copy", "ExternalLink",
    "Monitor", "History", "Bookmark", "Settings", "Trash2", "Files", "Globe",
    "Clock", "ArrowUpRight", "Star", "Download", "Type", "Maximize2",
    "CornerDownLeft", "ChevronDown", "FileText", "ArrowDownUp", "Maximize", "Layers",
    "Minus", "Sun", "Droplet", "Palette", "Grid2x2", "Link", "Link2", "Save",
    "ZoomIn", "ZoomOut", "ArrowUp", "Moon", "Pencil", "SlidersHorizontal",
]

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/kotlin/dev/voidapp/ui/icons/Lucide.kt"

src_root = pathlib.Path(sys.argv[1]) / "src/commonMain/kotlin/io/github/thelacspace/lucide/all"

HEADER = '''package dev.voidapp.ui.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathBuilder
import androidx.compose.ui.graphics.vector.path
import androidx.compose.ui.unit.dp

/**
 * The Lucide glyphs this app draws, generated by tools/gen_lucide.py straight
 * from the Lucide sources in https://github.com/thelacspace/lucide-compose
 * (v1.16.0). They are inlined because the published
 * `io.github.thelacspace:lucide-compose` artifact on Maven Central only contains
 * the generator's test icons.
 *
 * Same conventions as the library: 24x24 viewport, round caps and joins, stroke
 * only, 2.5f stroke (Lucide's 2f reads too thin at 16-20dp).
 */
object Lucide {
    private const val StrokeWidth = 2.5f

    /** Lucide's own default, for glyphs drawn at larger sizes. */
    private const val RegularStrokeWidth = 2f
'''


def to_kotlin(body: str) -> str:
    out = []
    for raw in body.splitlines():
        line = raw.strip()
        if not line:
            continue
        # "moveToRelative(21f, 21f)" -> "moveToRelative(21f, 21f)"
        line = line.replace("moveToRelative", "moveToRelative")
        out.append("            " + line)
    return "\n".join(out)


blocks = []
for name in ICONS:
    path = src_root / f"{name}.kt"
    text = path.read_text()
    # grab the strings inside lucidePath { ... } blocks
    calls = re.findall(r"lucidePath\(strokeWidth\) \{(.*?)\n\s*\}", text, re.S)
    if not calls:
        raise SystemExit(f"no paths parsed for {name}")
    body = "\n".join("lucidePath {\n" + c + "\n}" for c in calls)
    prop = name[0].upper() + name[1:]
    blocks.append(
        f"\n    val {prop}: ImageVector by lazy {{\n"
        f'        lucideIcon("{name}") {{\n'
        + to_kotlin(body) + "\n"
        "        }\n"
        "    }\n"
    )

FOOTER = '''
    private fun ImageVector.Builder.lucidePath(pathBuilder: PathBuilder.() -> Unit) = path(
        stroke = SolidColor(Color.Black),
        strokeLineWidth = StrokeWidth,
        strokeLineCap = StrokeCap.Round,
        strokeLineJoin = StrokeJoin.Round,
        pathBuilder = pathBuilder,
    )

    private fun lucideIcon(
        name: String,
        paths: ImageVector.Builder.() -> Unit,
    ): ImageVector = ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
    ).apply(paths).build()
}
'''

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(HEADER + "".join(blocks) + FOOTER)
print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} B, {len(ICONS)} icons)")
