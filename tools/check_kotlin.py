"""Lightweight static sanity checks for the Kotlin sources.

We cannot run Gradle in this workspace, so this catches the mistakes that are
cheap to detect textually: unused icon properties referenced but not generated,
composables referenced but not defined, duplicate package declarations, tabs of
obviously unbalanced braces, and imports of things that no longer exist.

Run: python3 tools/check_kotlin.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "app/src/main/kotlin"
errors = []
files = sorted(SRC.rglob("*.kt"))
print(f"scanning {len(files)} kotlin files")

# ---- collect defined symbols per package ---------------------------------
defined = {}          # simple name -> package
for path in files:
    text = path.read_text()
    pkg = re.search(r"^package\s+([\w.]+)", text, re.M).group(1)
    for match in re.finditer(r"^(?:public |internal |private )?(?:data class|object|class|interface|fun|val|enum class)\s+([A-Za-z_]\w*)", text, re.M):
        defined[match.group(1)] = pkg
    # members of objects
    for match in re.finditer(r"^\s{4}(?:val|fun)\s+([A-Za-z_]\w*)", text, re.M):
        defined.setdefault(match.group(1), pkg)

# ---- generated Lucide icons ---------------------------------------------
lucide_file = SRC / "dev/voidapp/ui/icons/Lucide.kt"
lucide_props = set(re.findall(r"^    val (\w+): ImageVector", lucide_file.read_text(), re.M))
print(f"Lucide icons generated: {len(lucide_props)}")

for path in files:
    rel = path.relative_to(ROOT)
    text = path.read_text()

    if len(re.findall(r"^package ", text, re.M)) != 1:
        errors.append(f"{rel}: more than one package declaration")

    # brace balance
    depth = 0
    stripped = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    stripped = re.sub(r'"(?:[^"\\]|\\.)*"', '""', stripped)
    stripped = re.sub(r"//[^\n]*", "", stripped)
    for ch in stripped:
        depth += (ch == "{") - (ch == "}")
        if depth < 0:
            errors.append(f"{rel}: unbalanced braces")
            break
    if depth != 0:
        errors.append(f"{rel}: braces do not close ({depth})")

    # every Lucide.X reference must exist
    for match in re.finditer(r"\bLucide\.(\w+)", text):
        name = match.group(1)
        if name not in lucide_props:
            errors.append(f"{rel}: Lucide.{name} is not generated")

    # imports that point at our own packages must resolve
    for match in re.finditer(r"^import (dev\.voidapp[\w.]*)\.(\w+)$", text, re.M):
        pkg, name = match.group(1), match.group(2)
        if name == "R":       # generated by AGP
            continue
        if name in ("DayEvent", "PageEntry", "Site", "SearchProvider"):
            continue          # data classes living next to their usage
        if name not in defined:
            errors.append(f"{rel}: import {pkg}.{name} not found in the project")

# ---- resources referenced but missing -----------------------------------
res = ROOT / "app/src/main/res"
strings = set(re.findall(r'name="(\w+)"', (res / "values/strings.xml").read_text()))
drawables = {p.stem for p in (res / "drawable").glob("*.xml")}
for path in files:
    rel = path.relative_to(ROOT)
    text = path.read_text()
    for key in re.findall(r"R\.string\.(\w+)", text):
        if key not in strings:
            errors.append(f"{rel}: R.string.{key} missing")
    for key in re.findall(r"R\.drawable\.(\w+)", text):
        if key not in drawables:
            errors.append(f"{rel}: R.drawable.{key} missing")

if errors:
    print("\n".join(f"FAIL {e}" for e in errors))
    sys.exit(1)
print("kotlin sources look consistent")

# ---- strings.xml: no duplicate keys (aapt rejects them) ----
import re as _re
_strings = ROOT / "app/src/main/res/values/strings.xml"
if _strings.exists():
    _names = _re.findall(r'name="([A-Za-z_0-9]+)"', _strings.read_text())
    _dups = sorted({n for n in _names if _names.count(n) > 1})
    for _d in _dups:
        print(f"FAIL duplicate <string> {_d}")
    if not _dups:
        print("strings.xml has no duplicate keys")
